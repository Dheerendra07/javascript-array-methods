let questions = [
  "What is html?",
  "What is css",
  "What is js",
  "What is node.js",
];

console.log(questions);

console.log(questions.at());

console.log(questions.at(1));
console.log(questions.at(-1)); //What is node.js

//Note : we use positive and negative both number in  at() method.
// Negative number return values from right to left.
